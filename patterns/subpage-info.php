<!-- wp:heading {"anchor":"genetics"} -->
<h2 class="wp-block-heading" id="genetics">Genetics</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>An inherited tendency can influence how hair changes over time. Some people notice a gradually receding hairline or thinning at the crown. A clinician can help distinguish a patterned change from other causes.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Note your family history, where thinning appears and when you first noticed it.</p>
<!-- /wp:paragraph -->

</div>
<!-- /wp:group -->
<!-- wp:group {"className":"dx-prose__section dx-stack","layout":{"type":"default"}} -->
<div class="wp-block-group dx-prose__section dx-stack">
<!-- wp:paragraph {"className":"dx-eyebrow"} -->
<p class="dx-eyebrow">02 / Stress</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"anchor":"stress"} -->
<h2 class="wp-block-heading" id="stress">Stress</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Significant physical or emotional stress may be followed by increased shedding. Timing varies, and other factors may be involved. If the change worries you, speak with a healthcare professional rather than assuming stress is the cause.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Keep a record of the timing and any other changes in your health or routine.</p>
<!-- /wp:paragraph -->

</div>
<!-- /wp:group -->
