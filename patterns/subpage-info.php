<h3 class="wp-block-heading" id="when-to-talk-to-a-doctor">When to talk to a doctor first</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Seek medical advice for sudden, patchy or unexplained hair loss, or scalp pain, redness or irritation. Dermatex can discuss cosmetic choices after medical concerns have been addressed.</p>
