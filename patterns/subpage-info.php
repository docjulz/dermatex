<p class="dx-eyebrow">03 / Your health</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"anchor":"medical-conditions"} -->
<h2 class="wp-block-heading" id="medical-conditions">Medical conditions</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Some health conditions can affect hair growth or the scalp. Patchy loss, discomfort or a rapid change is a reason to seek medical advice. A cosmetic consultation is not a substitute for a medical assessment.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Ask your healthcare professional which questions or tests, if any, are appropriate.</p>
<!-- /wp:paragraph -->

</div>
