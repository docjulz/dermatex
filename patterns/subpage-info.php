<p class="dx-eyebrow">04 / Medication</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"anchor":"medication"} -->
<h2 class="wp-block-heading" id="medication">Medication</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Certain medicines can be associated with changes in hair. Do not stop or adjust a prescribed medicine on your own. Your prescriber or pharmacist can discuss possible effects and safe next steps.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Bring an up-to-date list of medicines and supplements to your appointment.</p>
<!-- /wp:paragraph -->

</div>
